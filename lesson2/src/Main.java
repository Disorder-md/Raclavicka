public class Main {
    public static void main(String [] args){
        //int - Ціло число, 32 біта
        int myInt;
        myInt = 2795;
        System.out.println(myInt);
        int nomer = 7;
        System.out.println(nomer);
        //short - 16 bit
        short numb = 2345;
        System.out.println(numb);
        //long - 64 bit
        long longnumber = 234232;
        //double - 64 bit with .
        //float - 32 bit with .
        double myDouble = 27.95;
        float myFloat = 95.27f;
        //char - letter
        char m ='M';
        //boolean - true/false
        boolean love = true;
        //bite - 1 bit
        byte myByte = 127;
    }
}
